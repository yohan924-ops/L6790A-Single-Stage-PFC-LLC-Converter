             ['단락 인덕턴스 (= L<sub>r</sub>)', '%(Lr).0f µH' % K,
              '<b>%(Lshortx).2f µH</b>' % K, '1차 권선 → ×3'],
             ['자화 (= L<sub>m</sub>)', '%(Lm).0f µH' % K,
              '%(Lmx).2f µH' % K, '1차 권선 → ×3'],
             ['λ', '%(lam).2f' % K, '%(lam).2f' % K, '<b>동일</b>'],
             ['1차 턴', '%(NpT)d T' % K, '%(Npu)d T' % K, '권선 → 턴당'],
             ['2차 단권 턴', '%(Nsu)d T' % K, '%(Nsu)d T' % K, '분리단 → 동일'],
             ['보조 턴', '3 T', '1 T', '권선 → 턴당'],
