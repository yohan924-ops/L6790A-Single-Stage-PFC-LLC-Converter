"""트랜스포머 설계 정리 — 본문.

an_pdf.py 의 레이아웃을 그대로 쓰고 한국어 폰트만 갈아끼운다. 값은 전부
an_pdf.V 보간이라 시트가 바뀌면 이 문서도 따라온다 — 손으로 적은 숫자가
하나도 없어야 한다.

이 문서가 답하는 것은 하나다: "5 T : 2 T 가 어디서 나왔는가."
설계 가이드는 식을 다루고 AN 은 배포용이며, 이것은 그 사슬 하나를
처음부터 끝까지 따라가는 설명서다.
"""


def build(A):
    h1, h2, p, eq, fig, tbl, note = A.h1, A.h2, A.p, A.eq, A.fig, A.tbl, A.note
    bullets, V, CW = A.bullets, A.V, A.CW
    s = []
    add, ext = s.append, s.extend

    K = dict(V, nT=7.5, Npu=5, Nsu=2, Nx=3, NpT=15,
             Lopen=31.0, Lopenx=31.0/3, Lshortx=11.0/3, Lmx=20.0/3,
             k=0.8032, k2=0.6452, Vres=213.75, Vdrive=151.1,
             Isecx=V['Idio']/3, Ipri=V['Iprilc'])

    # =============================================================== 0
    add(h1('설계 사양 — 무엇을 위한 트랜스포머인가'))
    add(p('이 트랜스포머는 <b>L6790A 단일단(single-stage) PF LLC</b> TV SMPS 한 곳에만 '
          '쓰인다. 아래 사양을 벗어나면 이 문서의 결론(λ, n, n<sub>T</sub>, 5 T : 2 T)도 '
          '함께 바뀐다.'))
    add(tbl('설계 사양.',
            [['항목', '값'],
             ['입력', '%(Vacmin).0f ~ %(Vacmax).0f Vac (유니버설, 토폴로지 모핑)' % K],
             ['출력', '%(Vout).0f V / %(Iout).1f A = %(Pout).1f W' % K],
             ['용도', 'OLED 패널 구동 (TV SMPS)'],
             ['2차 정류', '센터탭 + SR (N<sub>rect</sub> = 1)'],
             ['컨트롤러', 'ST L6790A']],
            widths=[CW * 0.28, CW * 0.72]))
    add(p('<b>“단일단”이 이 문서의 출발점이다.</b> 기존 2단(부스트 PFC + LLC) 구성은 PFC '
          '단이 400&nbsp;V 벌크 커패시터를 만들어 LLC 탱크에 <b>거의 일정한 DC</b>를 넘겨준다. '
          '본 설계는 그 PFC 단과 벌크 커패시터를 통째로 없앤다 — 탱크가 <b>정류된 상용전원 '
          '사인파를 직접</b> 본다. 그 대가로 출력에 75&nbsp;mF 커패시터 뱅크가 붙지만, 그건 이 '
          '문서의 주제가 아니다(설계 가이드 참조).'))
    add(note('<b>이 한 가지 사실이 트랜스포머 설계 전체를 끌고 간다.</b> 벌크 커패시터가 '
             '없으니 탱크가 보는 입력이 라인사이클마다 0 근처까지 내려가고, 토폴로지 '
             '모핑까지 겹치면 등가 입력 범위가 <b>%(Veqlo).1f ~ %(Veqhi).1f&nbsp;Vac'
             '(약 1.92:1)</b>로 벌어진다. 2단 구성이라면 이 범위가 거의 0이다. 다음 절부터 '
             '이 범위 하나가 λ 와 결합도, 그리고 궁극적으로 권선비를 어떻게 정하는지 '
             '따라간다.' % K))

    # =============================================================== 1
    add(h1('이 트랜스포머가 특별한 이유'))
    add(p('보통 트랜스포머는 전압을 바꾸는 부품이라 권선비만 주면 끝나고, '
          '결합이 좋을수록 좋은 부품이다. LLC 는 다르다. 트랜스포머가 '
          '<b>공진 탱크의 일부</b>이고, 그 “결함”이 곧 회로 부품이다.'))
    ext(bullets([
        '<b>누설 인덕턴스 L<sub>r</sub></b> — 공진을 만드는 L. '
        'LLC 의 첫 번째 L 이다.',
        '<b>자화 인덕턴스 L<sub>m</sub></b> — ZVS 전류를 만드는 L. '
        '두 번째 L 이다.']))
    add(p('그래서 벤더에게 “잘 만들어 주세요”가 아니라 <b>“정확히 이만큼 새게 '
          '만들어 주세요”</b>라고 주문해야 한다. 이 문서는 그 “이만큼”이 '
          '어디서 나오는지를 처음부터 끝까지 따라간다.'))
    add(note('<b>결론부터.</b> 트랜스포머 1개당 <b>1차 %(Npu)d T · 2차 '
             '%(Nsu)d T + %(Nsu)d T · 보조 1 T</b>, 개방 인덕턴스 '
             '%(Lopenx).2f&nbsp;µH, 단락 인덕턴스 %(Lshortx).2f&nbsp;µH. '
             '3개를 1차 직렬 / 2차 병렬로 쓴다.' % K))

    # =============================================================== 2
    add(h1('출발점 — 입력이 넓다'))
    add(p('벌크 커패시터를 없앴으므로 공진 탱크가 정류된 사인파를 직접 본다. '
          '토폴로지 모핑까지 감안하면 탱크가 보는 등가 입력은 '
          '<b>%(Veqlo).1f ~ %(Veqhi).1f&nbsp;Vac</b>, 약 1.92 : 1 이다. '
          '2단 구성이라면 앞단 PFC 가 400&nbsp;V 를 고정해 주므로 이 범위가 '
          '거의 0 이다.' % K))
    add(p('설계점을 약 %(Vres).0f&nbsp;Vac 에 두고 그때 공진(게인 1)에서 돌게 '
          '하면, 양 끝에서 요구되는 게인은 이렇게 벌어진다.' % K))
    add(tbl('등가 입력 양 끝에서 요구되는 게인.',
            [['등가 입력', '요구 게인', ''],
             ['%(Veqlo).1f Vac' % K, '%(1).3f' % {'1': 1.2245}, '부스트'],
             ['%(Vacmax).0f Vac' % K, '%(1).3f' % {'1': 0.8035}, '벅']],
            widths=[CW * 0.34, CW * 0.33, CW * 0.33]))

